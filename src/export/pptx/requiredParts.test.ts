import { describe, expect, it } from "vitest";
import { buildPptxPackage, type PptxSlide } from "./package";
import { readZip, readZipText } from "./readZip.testutil";
import { slidePicture, slideXml } from "./slideZoom";
import { SLIDE_H_EMU, SLIDE_W_EMU } from "./ooxml";

// The part list PowerPoint actually needs, as opposed to the one the schema says is required.
//
// The first version of this exporter left out everything the schema marks optional and produced
// decks PowerPoint refused with "PowerPoint can't read <file>" — no element, no part, no clue.
// The list below is taken from a deck generated by a library whose output PowerPoint does open,
// which is the only ground truth obtainable without PowerPoint itself.
//
// Five of these are schema-optional. Do not remove one because a spec says it is not required:
// that is exactly the reasoning that produced the broken file.
const REQUIRED_PARTS = [
  "[Content_Types].xml",
  "_rels/.rels",
  "docProps/core.xml",
  "docProps/app.xml",
  "ppt/presentation.xml",
  "ppt/_rels/presentation.xml.rels",
  "ppt/presProps.xml",
  "ppt/viewProps.xml",
  "ppt/tableStyles.xml",
  "ppt/slideMasters/slideMaster1.xml",
  "ppt/slideMasters/_rels/slideMaster1.xml.rels",
  "ppt/slideLayouts/slideLayout1.xml",
  "ppt/slideLayouts/_rels/slideLayout1.xml.rels",
  "ppt/theme/theme1.xml",
];

const PNG = new Uint8Array([0x89, 0x50, 0x4e, 0x47]);

function deck(withNotes: boolean): PptxSlide[] {
  const body = slidePicture({
    shapeId: 2,
    name: "Diagram",
    frame: { x: 0, y: 0, w: SLIDE_W_EMU, h: SLIDE_H_EMU },
    imageRelId: "rId2",
  });
  const make = (title: string, image: string): PptxSlide => ({
    xml: slideXml({ title, body }),
    media: [{ fileName: image, bytes: PNG, relId: "rId2" }],
    ...(withNotes ? { notes: title } : {}),
  });
  return [make("Main", "image1.png"), make("Child", "image2.png")];
}

describe("the package carries every part PowerPoint needs", () => {
  it("includes all of them, notes or not", async () => {
    for (const withNotes of [true, false]) {
      const parts = await readZip(await buildPptxPackage(deck(withNotes)));
      for (const required of REQUIRED_PARTS) {
        expect([...parts.keys()], `${required} missing (notes: ${withNotes})`).toContain(required);
      }
    }
  });

  it("adds the notes master only when some slide has notes", async () => {
    const withNotes = await readZip(await buildPptxPackage(deck(true)));
    expect([...withNotes.keys()]).toContain("ppt/notesMasters/notesMaster1.xml");

    const without = await readZip(await buildPptxPackage(deck(false)));
    expect([...without.keys()].some((p) => p.includes("notesMaster"))).toBe(false);
  });

  // [Content_Types].xml has to be the first entry in the archive, not merely present.
  it("writes [Content_Types].xml as the first entry in the archive", async () => {
    const zip = await buildPptxPackage(deck(true));
    const firstName = new TextDecoder().decode(zip.subarray(30, 30 + new DataView(zip.buffer).getUint16(26, true)));
    expect(firstName).toBe("[Content_Types].xml");
  });

  it("declares a content type for every part it writes", async () => {
    const zip = await buildPptxPackage(deck(true));
    const types = await readZipText(zip, "[Content_Types].xml");
    for (const path of (await readZip(zip)).keys()) {
      if (path === "[Content_Types].xml") continue;
      const extension = path.slice(path.lastIndexOf(".") + 1);
      const covered = types.includes(`Extension="${extension}"`) || types.includes(`PartName="/${path}"`);
      expect(covered, `${path} has no content type`).toBe(true);
    }
  });

  it("points presentation.xml.rels at each of the optional-but-needed parts", async () => {
    const rels = await readZipText(await buildPptxPackage(deck(true)), "ppt/_rels/presentation.xml.rels");
    for (const target of ["presProps.xml", "viewProps.xml", "tableStyles.xml", "theme/theme1.xml"]) {
      expect(rels, `no relationship to ${target}`).toContain(`Target="${target}"`);
    }
  });

  it("gives the slide master the inherited text styles a real deck has", async () => {
    const master = await readZipText(await buildPptxPackage(deck(true)), "ppt/slideMasters/slideMaster1.xml");
    expect(master).toContain("<p:txStyles>");
    expect(master).toContain("<p:titleStyle>");
    expect(master).toContain("<p:bodyStyle>");
    expect(master).toContain("<p:otherStyle>");
  });

  // D74. Sharing one theme between the slide master and the notes master passed every check
  // here, and desktop PowerPoint refused every deck with notes as "corrupted and unreadable".
  it("gives every master a theme part of its own", async () => {
    const zip = await buildPptxPackage(deck(true));
    const masterRels = [...(await readZip(zip)).keys()].filter((p) => /Masters\/_rels\/[^/]+\.rels$/.test(p));
    expect(masterRels).toHaveLength(2); // slide master and notes master

    const themes = new Map<string, string>();
    for (const relsPath of masterRels) {
      const target = /Type="[^"]*\/theme" Target="([^"]+)"/.exec(await readZipText(zip, relsPath))?.[1];
      expect(target, `${relsPath} names no theme`).toBeDefined();
      expect(themes.get(target!), `${relsPath} shares ${target} with ${themes.get(target!)}`).toBeUndefined();
      themes.set(target!, relsPath);
      const part = `ppt/theme/${target!.split("/").pop()}`;
      expect([...(await readZip(zip)).keys()], `${part} is named but not written`).toContain(part);
    }
  });

  it("assigns every presentation relationship a distinct id", async () => {
    const rels = await readZipText(await buildPptxPackage(deck(true)), "ppt/_rels/presentation.xml.rels");
    const ids = [...rels.matchAll(/Id="([^"]+)"/g)].map((m) => m[1]);
    expect(new Set(ids).size).toBe(ids.length);
  });

  // Every r:id named inside presentation.xml must be one the rels part actually declares.
  it("keeps presentation.xml and its rels in agreement", async () => {
    const zip = await buildPptxPackage(deck(true));
    const pres = await readZipText(zip, "ppt/presentation.xml");
    const rels = await readZipText(zip, "ppt/_rels/presentation.xml.rels");
    const declared = new Set([...rels.matchAll(/Id="([^"]+)"/g)].map((m) => m[1]));

    for (const [, used] of pres.matchAll(/r:id="([^"]+)"/g)) {
      expect(declared, `presentation.xml uses ${used}, which its rels does not declare`).toContain(used);
    }
  });
});

export function notesMaster(): string {
  // The body placeholder each notes slide's own <p:ph type="body" idx="1"/> inherits from. A
  // slide placeholder whose master has no counterpart is an orphan.
  const bodyPlaceholder =
    "<p:sp>" +
    '<p:nvSpPr><p:cNvPr id="2" name="Notes Placeholder"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>' +
    '<p:nvPr><p:ph type="body" idx="1"/></p:nvPr></p:nvSpPr>' +
    '<p:spPr><a:xfrm><a:off x="685800" y="4343400"/><a:ext cx="5486400" cy="4114800"/></a:xfrm>' +
    '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>' +
    "<p:txBody><a:bodyPr/><a:lstStyle/><a:p/></p:txBody>" +
    "</p:sp>";

  const spTree =
    "<p:spTree>" +
    '<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>' +
    '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>' +
    bodyPlaceholder +
    "</p:spTree>";

  return (
    DECL +
    `<p:notesMaster xmlns:a="${NS_A}" xmlns:r="${NS_R}" xmlns:p="${NS_P}">` +
    `<p:cSld>${BACKGROUND}${spTree}</p:cSld>` +
    CLR_MAP +
    `<p:notesStyle>${textLevel(1, 1200, false)}</p:notesStyle>` +
    "</p:notesMaster>"
  );
}


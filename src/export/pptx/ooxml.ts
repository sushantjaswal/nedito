// The boilerplate parts a .pptx needs before PowerPoint will open it.
//
// Written by hand rather than via a library because the feature this export exists for —
// native Slide Zoom (see slideZoom.ts) — is an OOXML extension no library emits, so a library
// would have to be post-processed anyway.
//
// WHAT THIS FILE IS MODELLED ON. The first version was assembled from the schema alone, on the
// assumption that anything the schema marks optional could be left out. PowerPoint disagreed:
// it refused every deck with "PowerPoint can't read <file>", naming nothing. The parts below
// are now matched against a deck generated by a library whose output PowerPoint does open,
// which is the only ground truth available without PowerPoint itself. Two lessons from that
// comparison, both counter-intuitive:
//
//   * "Optional" in the schema is not optional in practice. presProps, viewProps, tableStyles
//     and the two docProps parts are all schema-optional and all present in a real file.
//   * The slide master genuinely needs <p:txStyles>. A master without it is schema-valid.
//
// requiredParts.test.ts pins the resulting part list so none of them can quietly go missing
// again.

/** English Metric Units per CSS pixel at 96dpi. 914400 EMU = 1 inch. */
export const EMU_PER_PX = 9525;

/** 16:9, PowerPoint's default since 2013. 13.333in x 7.5in. */
export const SLIDE_W_EMU = 12192000;
export const SLIDE_H_EMU = 6858000;

export function px(value: number): number {
  return Math.round(value * EMU_PER_PX);
}

/** XML text escaping. Diagram titles are user text and routinely contain & and <. */
export function esc(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

const DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n';

export const NS_P = "http://schemas.openxmlformats.org/presentationml/2006/main";
export const NS_A = "http://schemas.openxmlformats.org/drawingml/2006/main";
export const NS_R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";

const CT = "application/vnd.openxmlformats-officedocument";

export function contentTypes(slideCount: number, notesCount: number): string {
  const slides = Array.from(
    { length: slideCount },
    (_, i) => `<Override PartName="/ppt/slides/slide${i + 1}.xml" ContentType="${CT}.presentationml.slide+xml"/>`,
  ).join("");
  const notes = Array.from(
    { length: notesCount },
    (_, i) =>
      `<Override PartName="/ppt/notesSlides/notesSlide${i + 1}.xml" ContentType="${CT}.presentationml.notesSlide+xml"/>`,
  ).join("");
  const notesMaster = notesCount
    ? `<Override PartName="/ppt/notesMasters/notesMaster1.xml" ContentType="${CT}.presentationml.notesMaster+xml"/>` +
      `<Override PartName="/${NOTES_THEME_PART}" ContentType="${CT}.theme+xml"/>`
    : "";
  return (
    DECL +
    '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' +
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
    '<Default Extension="xml" ContentType="application/xml"/>' +
    '<Default Extension="png" ContentType="image/png"/>' +
    `<Override PartName="/ppt/presentation.xml" ContentType="${CT}.presentationml.presentation.main+xml"/>` +
    `<Override PartName="/ppt/slideMasters/slideMaster1.xml" ContentType="${CT}.presentationml.slideMaster+xml"/>` +
    `<Override PartName="/ppt/slideLayouts/slideLayout1.xml" ContentType="${CT}.presentationml.slideLayout+xml"/>` +
    `<Override PartName="/ppt/presProps.xml" ContentType="${CT}.presentationml.presProps+xml"/>` +
    `<Override PartName="/ppt/viewProps.xml" ContentType="${CT}.presentationml.viewProps+xml"/>` +
    `<Override PartName="/ppt/tableStyles.xml" ContentType="${CT}.presentationml.tableStyles+xml"/>` +
    `<Override PartName="/ppt/theme/theme1.xml" ContentType="${CT}.theme+xml"/>` +
    notesMaster +
    slides +
    notes +
    '<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>' +
    `<Override PartName="/docProps/app.xml" ContentType="${CT}.extended-properties+xml"/>` +
    "</Types>"
  );
}


/**
 * Slide ids start at 256 — PowerPoint's own floor for `p:sldId/@id`, and the value the Slide
 * Zoom's `sldId` attribute points at. The numbering here is therefore load-bearing, not
 * cosmetic: it is how a zoom names its destination.
 */
export const FIRST_SLIDE_ID = 256;

/** Relationship ids in presentation.xml.rels, kept in one place so the two agree. */
export function presentationRelIds(slideCount: number, hasNotes: boolean) {
  const slides = Array.from({ length: slideCount }, (_, i) => `rId${i + 2}`);
  let next = slideCount + 2;
  const notesMaster = hasNotes ? `rId${next++}` : null;
  return {
    slideMaster: "rId1",
    slides,
    notesMaster,
    presProps: `rId${next++}`,
    viewProps: `rId${next++}`,
    theme: `rId${next++}`,
    tableStyles: `rId${next++}`,
  };
}

export function presentation(slideCount: number, hasNotes: boolean): string {
  const ids = presentationRelIds(slideCount, hasNotes);
  const sldIds = ids.slides.map((rid, i) => `<p:sldId id="${FIRST_SLIDE_ID + i}" r:id="${rid}"/>`).join("");
  const notesMasterId = ids.notesMaster
    ? `<p:notesMasterIdLst><p:notesMasterId r:id="${ids.notesMaster}"/></p:notesMasterIdLst>`
    : "";
  // CT_Presentation is an xsd:sequence: sldMasterIdLst, notesMasterIdLst, handoutMasterIdLst,
  // sldIdLst, sldSz, notesSz. (PowerPoint turns out to tolerate the last two swapped — a
  // library whose output it accepts emits them the other way round — but schema order is the
  // one that is correct by definition, so that is what this writes.)
  return (
    DECL +
    `<p:presentation xmlns:a="${NS_A}" xmlns:r="${NS_R}" xmlns:p="${NS_P}" saveSubsetFonts="1">` +
    `<p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="${ids.slideMaster}"/></p:sldMasterIdLst>` +
    notesMasterId +
    `<p:sldIdLst>${sldIds}</p:sldIdLst>` +
    `<p:sldSz cx="${SLIDE_W_EMU}" cy="${SLIDE_H_EMU}"/>` +
    '<p:notesSz cx="6858000" cy="9144000"/>' +
    "</p:presentation>"
  );
}

export function presentationRels(slideCount: number, hasNotes: boolean): string {
  const ids = presentationRelIds(slideCount, hasNotes);
  const slides = ids.slides
    .map((rid, i) => `<Relationship Id="${rid}" Type="${NS_R}/slide" Target="slides/slide${i + 1}.xml"/>`)
    .join("");
  const notesMaster = ids.notesMaster
    ? `<Relationship Id="${ids.notesMaster}" Type="${NS_R}/notesMaster" Target="notesMasters/notesMaster1.xml"/>`
    : "";
  return (
    DECL +
    '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' +
    `<Relationship Id="${ids.slideMaster}" Type="${NS_R}/slideMaster" Target="slideMasters/slideMaster1.xml"/>` +
    slides +
    notesMaster +
    `<Relationship Id="${ids.presProps}" Type="${NS_R}/presProps" Target="presProps.xml"/>` +
    `<Relationship Id="${ids.viewProps}" Type="${NS_R}/viewProps" Target="viewProps.xml"/>` +
    `<Relationship Id="${ids.theme}" Type="${NS_R}/theme" Target="theme/theme1.xml"/>` +
    `<Relationship Id="${ids.tableStyles}" Type="${NS_R}/tableStyles" Target="tableStyles.xml"/>` +
    "</Relationships>"
  );
}

const EMPTY_SP_TREE =
  "<p:spTree>" +
  '<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>' +
  '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>' +
  "</p:spTree>";

const BACKGROUND = '<p:bg><p:bgRef idx="1001"><a:schemeClr val="bg1"/></p:bgRef></p:bg>';

const CLR_MAP =
  '<p:clrMap bg1="lt1" tx1="dk1" bg2="lt2" tx2="dk2" accent1="accent1" accent2="accent2" accent3="accent3"' +
  ' accent4="accent4" accent5="accent5" accent6="accent6" hlink="hlink" folHlink="folHlink"/>';

/** One text-style level, as the master's title/body/other styles each need at least one. */
function textLevel(level: number, size: number, major: boolean): string {
  const face = major ? "+mj" : "+mn";
  return (
    `<a:lvl${level}pPr marL="0" algn="l" defTabSz="914400" rtl="0" eaLnBrk="1" latinLnBrk="0" hangingPunct="1">` +
    '<a:spcBef><a:spcPct val="0"/></a:spcBef><a:buNone/>' +
    `<a:defRPr sz="${size}" kern="1200"><a:solidFill><a:schemeClr val="tx1"/></a:solidFill>` +
    `<a:latin typeface="${face}-lt"/><a:ea typeface="${face}-ea"/><a:cs typeface="${face}-cs"/></a:defRPr>` +
    `</a:lvl${level}pPr>`
  );
}

/**
 * The master's inherited text styles. Schema-optional; absent from the first version of this
 * exporter and present in every real deck. Only level 1 of each is defined — nothing in a
 * diagram export inherits deeper than that.
 */
function txStyles(): string {
  return (
    "<p:txStyles>" +
    `<p:titleStyle>${textLevel(1, 4400, true)}</p:titleStyle>` +
    `<p:bodyStyle>${textLevel(1, 1800, false)}</p:bodyStyle>` +
    `<p:otherStyle>${textLevel(1, 1800, false)}</p:otherStyle>` +
    "</p:txStyles>"
  );
}

